"""Task three_x_ui_xray_setup: wrap the official 3x-ui installer.

The task deploys the 3x-ui Xray panel as a system service by wrapping
the official install.sh of the configured repository. The newest release
tag comes from the GitHub releases API
(https://api.github.com/repos/{repo}/releases/latest); the task compares
it with the installed version read from the x-ui binary and with the
enabled and active state of the service. When the installed version
equals the newest release tag and the service is already enabled and
active, the task returns a plain done result with changed=False: the
official installer always tears the panel down and rebuilds it, so it
must not be run on a working panel just to confirm the state. Otherwise
the task frees the fixed panel port (stopping the x-ui service when it
owns the port, terminating an unknown process), downloads the official
install.sh and runs it in non-interactive mode (XUI_NONINTERACTIVE=1)
with the proquint credentials and the panel port passed as env vars
(XUI_USERNAME, XUI_PASSWORD, XUI_WEB_BASE_PATH, XUI_PANEL_PORT). The
installer applies them on first deployment and preserves the current
values on an existing panel with custom credentials, so a rerun never
rotates them.

Stage 2 reads the credentials the panel generated on first start from
/etc/x-ui/install-result.env, logs in through the panel REST API to
verify the session, and stores the credentials in the runtime vault
(/var/lib/pyntara/secrets/pyntara.vault) in a single KeePass entry
named by vault_entry_title. The username and password fields carry the
panel admin credentials; the url field carries the panel base URL; the
notes field carries the additional values (XUI_PANEL_PORT,
XUI_WEB_BASE_PATH, XUI_API_TOKEN, XUI_DB_TYPE) as key=value lines.
Stage 2 runs after every install and on every rerun where the target
state is already reached, so the vault entry is always up to date.

Stage 3 creates a VLESS+REALITY inbound on the configured port through
the panel Bearer-token API. The REALITY keypair is generated through
the panel's getNewX25519Cert endpoint; the private and public keys are
appended to the vault entry notes. On a rerun the task finds the
existing inbound by port and returns done without creating a duplicate.

Stage 4 ensures the panel serves HTTPS when ssl_enabled. A trusted
Let's Encrypt IP certificate is issued when the HTTP-01 challenge can
reach the machine: a machine with a public address on an interface (a
VPS) or a confirmed port-80 forward runs the installer with
XUI_SSL_MODE=ip; a machine behind NAT without a forward gets a
self-signed certificate generated by the task, so the panel never
serves plain HTTP. On a rerun where the installer is skipped, the stage
checks `x-ui setting -getCert`, issues the certificate through acme.sh
when the panel has none, replaces a self-signed certificate with a
trusted one as soon as port 80 becomes reachable, and otherwise keeps
the existing certificate. The result tells the user honestly whether
the certificate is trusted or self-signed and how to obtain a trusted
one. After the installer (and on a rerun) the task brings the panel to
the configured port, migrating it when an earlier install left it on
another port, and syncs install-result.env so its port and scheme match
reality. In force mode on an existing panel the task also applies fresh
proquint credentials and webBasePath directly through `x-ui setting`,
because the installer preserves them on a non-default panel; normal runs
never touch them.

Stage 6 makes this machine a client of the remote server whose vless link
sits in the vault entry named by client_profile_entry_title: the panel
already runs Xray here, so the client is one inbound of that panel that
serves SOCKS5 and HTTP on a local address, and no second Xray process is
installed. Stage 7 routes what enters that inbound: advertising is
dropped, .onion goes to the local tor proxy and .i2p to the local i2pd
proxy, the machine's own names and networks go directly, and the rest
depends on the country the configured services report. A machine outside
Russia sends everything else to the remote server; a machine in Russia
sends the resources blocked there and the services that refuse to serve
Russia through the remote server, reaches what only answers inside Russia
directly, and sends everything else directly as well. Every category
token is checked against the geodata the panel installed before it is
applied, and every class of destination is then verified against the
running core with its routing test, because the core can hold a rule set
the stored template no longer matches. The machine that is the remote
server itself skips both stages: it does not connect to itself.
"""

