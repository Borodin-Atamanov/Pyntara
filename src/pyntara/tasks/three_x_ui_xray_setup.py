def _install_or_reuse(
    ctx: Context,
    cfg: ThreeXuiXraySetupConfig,
    engine: EngineConfig,
    timeout: float,
    force: bool,
    facts: _RunFacts,
) -> tuple[TaskResult, list[str]]:
    """Reach the target state of the panel, or leave the panel that is there.

    The goal is reached when the installed version equals the newest
    release tag and the service is enabled and active; the task then
    changes nothing, because the official installer always tears the panel
    down and rebuilds it. Otherwise the fixed panel port and, when the
    HTTP-01 challenge can reach this machine, the ACME port are freed, the
    official install.sh runs non-interactively with the proquint
    credentials, the service is awaited, and force mode applies the fresh
    credentials and webBasePath to an existing panel. Returns the result
    of this part and the warnings it collected: a release that cannot be
    read, a busy port, a failed download, a failed run and a service that
    does not become active are warnings of a completed task, and the panel
    stages still run afterwards on the panel that is there.
    """

    install_warnings: list[str] = []
    _log(f"querying the latest release of {cfg.github_repo}")
    tag = ""
    release: dict[str, object] = {}
    try:
        release = fetch_latest_release(cfg.github_repo, ctx.config.engine)
        tag = release_tag(release)
    except RuntimeError as exc:
        # Without the release tag the installed version cannot be compared,
        # so the installer is skipped; the panel that is there is still
        # converged and every stage below still runs.
        install_warnings.append(str(exc))
    if tag:
        _log(f"checking latest release: {tag}")
    else:
        _log("latest release unknown, the installer step is skipped")

    _log("reading the installed panel version")
    installed_version = _installed_version(cfg, timeout)
    _log(
        f"checking installed version: {installed_version or 'not installed'}"
    )

    enabled = service_is_enabled(ctx.config.engine, cfg.service_unit_name, timeout)
    active = service_is_active(ctx.config.engine, cfg.service_unit_name, timeout)
    _log(
        f"checking autorun service {cfg.service_unit_name}: "
        f"{'enabled' if enabled else 'disabled'}"
    )
    _log(f"checking service status: {'active' if active else 'inactive'}")

    rerun = (
        bool(tag)
        and not force
        and installed_version == version_without_tag_prefix(tag)
        and enabled
        and active
    )
    ssl_attempt = False
    if rerun:
        _log("target state already reached")
        result = TaskResult(
            success=True,
            changed=False,
            message="target state already reached",
            warnings=tuple(install_warnings),
        )
    else:
        installer_ready = bool(tag)
        if installer_ready:
            # The panel binds the fixed port, so the port must be free
            # before the installer runs: stop x-ui when it owns the port,
            # terminate an unknown process.
            _log(f"checking panel port {cfg.panel_port} is free")
            try:
                freed = ensure_port_free(
                    ctx.config.engine,
                    cfg.panel_port,
                    cfg.service_unit_name,
                    timeout,
                    service_process_name=cfg.service_process_name,
                )
            except RuntimeError as exc:
                install_warnings.append(str(exc))
                installer_ready = False
            else:
                if freed:
                    _log(f"panel port {cfg.panel_port}: {freed}")

        # Decide whether the Let's Encrypt HTTP-01 challenge can reach
        # this machine before passing XUI_SSL_MODE. A machine behind NAT
        # (only private addresses on its interfaces) cannot serve the
        # challenge unless the router forwards port 80; when it cannot,
        # the installer skips the certificate and the panel gets a
        # self-signed one after the install (stage 4), never plain HTTP.
        if cfg.ssl_enabled and installer_ready:
            ssl_attempt = _ssl_reachable(cfg, timeout, facts)

        # The installer's SSL step runs the ACME HTTP-01 challenge on
        # port 80 and fails in non-interactive mode when the port is
        # busy, so the port must be free before the installer runs.
        if installer_ready and ssl_attempt:
            _log(f"checking ACME port {cfg.acme_port} is free")
            try:
                freed = ensure_port_free(
                    ctx.config.engine,
                    cfg.acme_port,
                    cfg.service_unit_name,
                    timeout,
                    service_process_name=cfg.service_process_name,
                )
            except RuntimeError as exc:
                # Only the certificate step depends on this port: the
                # installer still runs without an SSL attempt.
                install_warnings.append(str(exc))
                ssl_attempt = False
            else:
                if freed:
                    _log(f"ACME port {cfg.acme_port}: {freed}")

        script_path: Path | None = None
        if installer_ready:
            _log(f"downloading installer {cfg.install_script_url}")
            try:
                script_path = _download_installer(
                    ctx.config.engine,
                    cfg,
                    timeout,
                )
            except RuntimeError as exc:
                install_warnings.append(str(exc))
        if script_path is None:
            result = TaskResult(
                success=True,
                changed=False,
                message="; ".join(install_warnings) or "installer skipped",
                warnings=tuple(install_warnings),
            )
        else:
            _log("installer downloaded")
            if ssl_attempt:
                _log(f"installer will attempt a certificate on port {cfg.acme_port}")

            _log("running official 3x-ui installer with proquint credentials")
            installer_env = _credential_env(cfg)
            if cfg.ssl_enabled:
                installer_env["XUI_SSL_MODE"] = "ip" if ssl_attempt else "none"
            installed_now = True
            try:
                _run_installer(cfg, script_path, timeout, installer_env)
            except (subprocess.CalledProcessError, subprocess.TimeoutExpired) as exc:
                install_warnings.append(f"installer failed: {exc}")
                installed_now = False
            if not installed_now:
                result = TaskResult(
                    success=True,
                    changed=False,
                    message="; ".join(install_warnings),
                    warnings=tuple(install_warnings),
                )
            else:
                _log("installer finished")

                _log(
                    f"waiting for service to become active (up to "
                    f"{cfg.service_start_wait_seconds} s)"
                )
                if not _wait_active(
                    ctx.config.engine,
                    cfg.service_unit_name,
                    cfg.service_start_wait_seconds,
                    cfg.readiness_check_delay_seconds,
                    timeout,
                ):
                    install_warnings.append(
                        f"service {cfg.service_unit_name} did not become active "
                        f"after the installer"
                    )
                _log(f"checking installed version: {_installed_version(cfg, timeout)}")
                # Force takeover: the installer preserves credentials and
                # webBasePath on an existing non-default panel, so force applies
                # the fresh proquint values it generated for the installer
                # directly. A fresh install already received them from the
                # installer environment.
                takeover_note = ""
                if force and installed_version is not None:
                    takeover_ok, takeover_message = _takeover_credentials(
                        cfg, timeout, installer_env
                    )
                    if takeover_ok:
                        _log(takeover_message)
                        takeover_note = f"; {takeover_message}"
                    elif takeover_message:
                        install_warnings.append(
                            f"panel credential takeover failed: {takeover_message}"
                        )
                result = TaskResult(
                    success=True,
                    changed=True,
                    message=f"installed 3x-ui {tag}{takeover_note}",
                    warnings=tuple(install_warnings),
                )

    return result, install_warnings


def _fold_stage(
    result: TaskResult, stage: TaskResult | None
) -> tuple[tuple[str, ...], bool]:
    """Fold one stage result into the result of the whole task.

    The message of the stage is appended to the message of the task, so a
    rerun reads as the list of what each stage did, and the warnings and
    the changed flag are handed back for the caller to collect. None, the
    answer of a stage that found everything already in place, folds in
    nothing.
    """

    if stage is None:
        return (), False
    if stage.message:
        result.message = "; ".join(
            part for part in (result.message, stage.message) if part
        )
    return stage.warnings or (), stage.changed


def _run_panel_stages(
    ctx: Context,
    cfg: ThreeXuiXraySetupConfig,
    engine: EngineConfig,
    timeout: float,
    facts: _RunFacts,
    result: TaskResult,
    install_warnings: list[str],
    force: bool,
) -> TaskResult:
    """Run every panel stage and merge their results into one answer.

    The panel port is brought to the configured value and install-result.env
    is synced with reality, the HTTPS stage runs, then stage 2 stores the
    panel credentials, the subscription paths are moved off the defaults,
    stage 3 creates the universal inbound, stage 5 ensures the client and
    the connection profile, and stages 6 and 7 give the machine its local
    proxy with the routing policy and the pool of remote exits. Every stage
    reports its own warnings instead of failing, so one dead step leaves
    the rest of the machine configured. force writes the objects of the
    client half even when they already match, which is the lever an operator
    has when the running core disagrees with what the panel stores. Returns
    the merged result.
    """

    # Bring the panel to the configured port and sync install-result.env
    # so its port and scheme match reality. Runs in both paths: a rerun
    # can find a panel on a port left by an earlier install, and the
    # installer preserves an existing port on a reinstall.
    try:
        converged, converged_message = _converge_panel_port(
            ctx.config.engine, cfg, timeout
        )
    except RuntimeError as exc:
        # The panel port could not be converged: every stage below talks to
        # the panel through its REST API and reports its own result.
        install_warnings.append(str(exc))
    else:
        if converged:
            _log(f"panel port: {converged_message}")
            result.changed = True
            result.message = (result.message or "") + f"; {converged_message}"
    # A port migration restarts the panel; the HTTP listener can trail
    # the systemd active state by a moment, so stage 2 would otherwise
    # report a false login failure. Wait for the listener before it.
    _wait_panel_http(cfg, timeout)

    # Ensure the panel serves HTTPS (a trusted certificate when port 80
    # is reachable, a self-signed one otherwise) before stage 2, so the
    # stored scheme and url are correct on the first run. The stage may
    # restart the panel, so the listener is polled again after it.
    ssl_result = _stage_ssl(engine, cfg, timeout, facts)
    ssl_warnings, ssl_changed = _fold_stage(result, ssl_result)
    if ssl_result is not None:
        _wait_panel_http(cfg, timeout)

    # Sync install-result.env so its port and scheme match reality: the
    # port after the convergence, the scheme after the HTTPS stage set
    # the certificate.
    _sync_install_result_env(cfg, timeout)

    # Stage 2: read credentials, verify session, store in vault. The stage
    # reports only warnings, so its changed flag is not collected.
    stage2_warnings, _ = _fold_stage(
        result, _stage2(cfg, ctx.config, timeout)
    )

    # Panel settings: move the subscription paths off the well-known
    # defaults so the panel does not warn about them. A failure here is a
    # warning, not an error: the panel keeps working with the defaults.
    settings_changed = False
    settings_warnings: tuple[str, ...] = ()
    settings_result: tuple[bool, str] | None = None
    try:
        settings_result = _stage_settings(cfg, timeout)
    except RuntimeError as exc:
        settings_warnings = (f"panel subscription paths not set: {exc}",)
    if settings_result is not None:
        settings_changed = settings_result[0]
        if settings_result[1]:
            _log(f"subscription paths: {settings_result[1]}")
            result.message = "; ".join(
                part for part in (result.message, settings_result[1]) if part
            )

    # Stage 3: create the universal server inbound. The payload document
    # comes from task_data/ of the clone, so an unreadable template is a
    # warning and the remaining stages still run.
    stage3_warnings: tuple[str, ...] = ()
    stage3_changed = False
    try:
        payload_template = _read_inbound_payload_template(cfg, ctx)
    except OSError as exc:
        stage3_warnings = (f"inbound payload template not read: {exc}",)
    else:
        stage3_warnings, stage3_changed = _fold_stage(
            result, _stage3(cfg, payload_template, timeout)
        )

    # Stage 5: ensure the panel client and store the connection profile.
    connection_warnings, connection_changed = _fold_stage(
        result,
        _stage_connection(cfg, ctx.config, timeout, facts, force=force),
    )

    # Stage 6: serve the local proxy of this machine through the panel,
    # and stage 7: write the routing policy and the pool of remote exits
    # and verify them. Both run on every machine; the machine that is the
    # remote server itself gets no outbound to itself, so its pool falls
    # back to the direct outbound.
    proxy_warnings, proxy_changed = _fold_stage(
        result, _stage_local_proxy(cfg, timeout, force=force)
    )

    routing_warnings, routing_changed = _fold_stage(
        result, _stage_routing_policy(cfg, ctx, timeout, facts, force=force)
    )

    # The install warnings already travel inside the result of the install
    # step, so they are listed once here; adding result.warnings as well
    # would print every install warning twice.
    all_warnings = (
        tuple(install_warnings)
        + ssl_warnings
        + stage2_warnings
        + settings_warnings
        + stage3_warnings
        + connection_warnings
        + proxy_warnings
        + routing_warnings
    )
    changed_by_a_stage = (
        ssl_changed
        or settings_changed
        or stage3_changed
        or connection_changed
        or proxy_changed
        or routing_changed
    )
    if all_warnings or changed_by_a_stage:
        return TaskResult(
            success=True,
            changed=result.changed or changed_by_a_stage,
            message=result.message,
            warnings=all_warnings or (),
        )
    return result


def task(ctx: Context) -> TaskResult:
    """Set up the 3x-ui panel of this machine and report what changed.

    The run facts are collected once, the panel is installed or left as it
    is, and every panel stage then runs on the panel that is there. The
    subjects themselves live in the pyntara.xray_* modules: the panel as a
    service, the facts about this machine, the HTTPS, the server half and
    the client half with its pool (docs/spec/3x-ui.md). A step that cannot
    run is a warning of a completed task, so the runner continues with the
    remaining tasks and never stops here.
    """

    cfg = ctx.config.three_x_ui_xray_setup
    engine = ctx.config.engine
    timeout = ctx.config.engine.command_timeout_seconds
    force = ctx.task_name in ctx.force_tasks

    # Addresses and the UPnP router are read once per run: the stages reuse
    # them, so a machine without UPnP is not asked about its router for
    # every port and the echo services are queried once.
    facts = _collect_run_facts(engine, cfg, timeout)
    facts = replace(
        facts,
        client_address=_forward_upnp_ports(engine, cfg, facts, timeout),
    )
    result, install_warnings = _install_or_reuse(
        ctx, cfg, engine, timeout, force, facts
    )
    return _run_panel_stages(
        ctx, cfg, engine, timeout, facts, result, install_warnings, force
    )
